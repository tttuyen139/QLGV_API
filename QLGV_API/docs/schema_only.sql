-- Chọn database ĐÍCH MỚI trong SSMS trước khi chạy. Không đổi database nguồn.
SET XACT_ABORT ON;
BEGIN TRANSACTION;
CREATE TABLE dbo.KHOA (
 MAKHOA VARCHAR(4) NOT NULL CONSTRAINT PK_KHOA PRIMARY KEY,
 TENKHOA NVARCHAR(40) NOT NULL, NGTLAP SMALLDATETIME NOT NULL, TRGKHOA CHAR(4) NULL
);
CREATE TABLE dbo.GIAOVIEN (
 MAGV CHAR(4) NOT NULL CONSTRAINT PK_GIAOVIEN PRIMARY KEY,
 HOTEN NVARCHAR(40) NOT NULL, HOCVI NVARCHAR(10) NOT NULL, HOCHAM NVARCHAR(10) NULL,
 GIOITINH NVARCHAR(3) NOT NULL, NGSINH SMALLDATETIME NOT NULL, NGVL SMALLDATETIME NOT NULL,
 HESO NUMERIC(4,2) NOT NULL, MUCLUONG MONEY NOT NULL, MAKHOA VARCHAR(4) NOT NULL,
 CONSTRAINT FK_GIAOVIEN_KHOA FOREIGN KEY(MAKHOA) REFERENCES dbo.KHOA(MAKHOA),
 CONSTRAINT CK_GV_GIOITINH CHECK(GIOITINH IN (N'Nam',N'Nữ')),
 CONSTRAINT CK_GV_HESO CHECK(HESO>0), CONSTRAINT CK_GV_LUONG CHECK(MUCLUONG>=0),
 CONSTRAINT CK_GV_NGAY CHECK(NGVL>NGSINH)
);
CREATE TABLE dbo.MONHOC (
 MAMH VARCHAR(10) NOT NULL CONSTRAINT PK_MONHOC PRIMARY KEY, TENMH NVARCHAR(40) NOT NULL,
 TCLT TINYINT NOT NULL, TCTH TINYINT NOT NULL, MAKHOA VARCHAR(4) NOT NULL,
 CONSTRAINT FK_MONHOC_KHOA FOREIGN KEY(MAKHOA) REFERENCES dbo.KHOA(MAKHOA)
);
CREATE TABLE dbo.DIEUKIEN (
 MAMH VARCHAR(10) NOT NULL, MAMH_TRUOC VARCHAR(10) NOT NULL,
 CONSTRAINT PK_DIEUKIEN PRIMARY KEY(MAMH,MAMH_TRUOC),
 CONSTRAINT FK_DK_MONHOC FOREIGN KEY(MAMH) REFERENCES dbo.MONHOC(MAMH),
 CONSTRAINT FK_DK_MONHOC_TRUOC FOREIGN KEY(MAMH_TRUOC) REFERENCES dbo.MONHOC(MAMH),
 CONSTRAINT CK_DK_KHACMON CHECK(MAMH<>MAMH_TRUOC)
);
CREATE TABLE dbo.LOP (
 MALOP CHAR(3) NOT NULL CONSTRAINT PK_LOP PRIMARY KEY, TENLOP NVARCHAR(40) NOT NULL,
 TRGLOP CHAR(5) NULL, SISO TINYINT NOT NULL, MAGVCN CHAR(4) NOT NULL,
 CONSTRAINT FK_LOP_GIAOVIEN FOREIGN KEY(MAGVCN) REFERENCES dbo.GIAOVIEN(MAGV)
);
CREATE TABLE dbo.HOCVIEN (
 MAHV CHAR(5) NOT NULL CONSTRAINT PK_HOCVIEN PRIMARY KEY, HO NVARCHAR(40) NOT NULL,
 TEN NVARCHAR(10) NOT NULL, NGSINH SMALLDATETIME NOT NULL, GIOITINH NVARCHAR(3) NOT NULL,
 NOISINH NVARCHAR(40) NOT NULL, MALOP CHAR(3) NOT NULL,
 CONSTRAINT FK_HOCVIEN_LOP FOREIGN KEY(MALOP) REFERENCES dbo.LOP(MALOP),
 CONSTRAINT CK_HV_GIOITINH CHECK(GIOITINH IN (N'Nam',N'Nữ'))
);
CREATE TABLE dbo.GIANGDAY (
 MALOP CHAR(3) NOT NULL, MAMH VARCHAR(10) NOT NULL, MAGV CHAR(4) NOT NULL,
 HOCKY TINYINT NOT NULL, NAM SMALLINT NOT NULL,
 TUNGAY SMALLDATETIME NOT NULL, DENNGAY SMALLDATETIME NOT NULL,
 CONSTRAINT PK_GIANGDAY PRIMARY KEY(MALOP,MAMH),
 CONSTRAINT FK_GD_LOP FOREIGN KEY(MALOP) REFERENCES dbo.LOP(MALOP),
 CONSTRAINT FK_GD_MONHOC FOREIGN KEY(MAMH) REFERENCES dbo.MONHOC(MAMH),
 CONSTRAINT FK_GD_GIAOVIEN FOREIGN KEY(MAGV) REFERENCES dbo.GIAOVIEN(MAGV),
 CONSTRAINT CK_GD_HOCKY CHECK(HOCKY BETWEEN 1 AND 3),
 CONSTRAINT CK_GD_NGAY CHECK(TUNGAY<=DENNGAY)
);
CREATE TABLE dbo.KETQUATHI (
 MAHV CHAR(5) NOT NULL, MAMH VARCHAR(10) NOT NULL, LANTHI TINYINT NOT NULL,
 NGTHI SMALLDATETIME NOT NULL, DIEM NUMERIC(4,2) NOT NULL, KQUA NVARCHAR(10) NOT NULL,
 CONSTRAINT PK_KETQUATHI PRIMARY KEY(MAHV,MAMH,LANTHI),
 CONSTRAINT FK_KQT_HOCVIEN FOREIGN KEY(MAHV) REFERENCES dbo.HOCVIEN(MAHV),
 CONSTRAINT FK_KQT_MONHOC FOREIGN KEY(MAMH) REFERENCES dbo.MONHOC(MAMH),
 CONSTRAINT CK_KQT_LANTHI CHECK(LANTHI>=1),
 CONSTRAINT CK_KQT_DIEM CHECK(DIEM BETWEEN 0 AND 10),
 CONSTRAINT CK_KQT_KQUA CHECK((DIEM>=5 AND KQUA=N'Đạt') OR (DIEM<5 AND KQUA=N'Không đạt'))
);
ALTER TABLE dbo.KHOA ADD CONSTRAINT FK_KHOA_TRUONGKHOA FOREIGN KEY(TRGKHOA) REFERENCES dbo.GIAOVIEN(MAGV);
ALTER TABLE dbo.LOP ADD CONSTRAINT FK_LOP_TRUONGLOP FOREIGN KEY(TRGLOP) REFERENCES dbo.HOCVIEN(MAHV);
COMMIT;
